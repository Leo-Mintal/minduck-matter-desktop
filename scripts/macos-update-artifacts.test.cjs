const assert = require('node:assert/strict')
const crypto = require('node:crypto')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const test = require('node:test')
const { readUpdateManifest, refreshUpdateManifest, verifyUpdateArtifacts } = require('./macos-update-artifacts.cjs')

test('final manifest covers final stapled DMG bytes and the unchanged update ZIP', t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'minduck-update-manifest-'))
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const version = '0.1.8', zip = `MinduckMatter-${version}-arm64.zip`, dmg = zip.replace('.zip', '.dmg')
  fs.writeFileSync(path.join(root, zip), 'signed notarized zip')
  fs.writeFileSync(path.join(root, dmg), 'final stapled dmg')
  const manifest = path.join(root, 'latest-mac.yml')
  fs.writeFileSync(manifest, JSON.stringify({ version, files: [], releaseDate: '2026-11-12T00:00:00Z' }))
  refreshUpdateManifest(root, version)
  const info = readUpdateManifest(manifest)
  assert.equal(info.path, zip)
  assert.equal(info.releaseDate, '2026-11-12T00:00:00Z')
  for (const entry of info.files) {
    const bytes = fs.readFileSync(path.join(root, entry.url))
    assert.equal(entry.sha512, crypto.createHash('sha512').update(bytes).digest('base64'))
    assert.equal(entry.size, bytes.length)
  }
  assert.throws(() => refreshUpdateManifest(root, '0.1.9'), /不符/)
  assert.equal(verifyUpdateArtifacts(root, manifest, version).version, version)
  fs.appendFileSync(path.join(root, zip), 'corrupted')
  assert.throws(() => verifyUpdateArtifacts(root, manifest, version), /校验失败/)
})
